--  Older versions of this file created a fully permissive policy
--  ("public read events" ... using (true)). RLS policies are OR-ed,
--  so if that leftover is still on the project, private events stay
--  readable by everyone. Drop EVERY existing read policy on events
--  first, then recreate the correct ones below. (Safe to re-run.)
do $$
declare pol record;
begin
  for pol in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename  = 'events'
      and cmd in ('SELECT', '*')
  loop
    execute format('drop policy if exists %I on public.events', pol.policyname);
  end loop;
end $$;

