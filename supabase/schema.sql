-- Drop the old trips table if migrating from a previous version
drop table if exists public.trips;

-- Events (game nights / social gatherings)
create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  date        date,
  time        text,
  location    text,
  image       text,
  price       numeric,
  guidelines  text,
  created_at  timestamptz default now()
);

-- Migrate existing projects (safe to re-run)
alter table public.events add column if not exists price      numeric;
alter table public.events add column if not exists guidelines text;
alter table public.events drop column if exists available;

-- Bookings (instant guest checkout - no accounts)
create table if not exists public.bookings (
  id          bigint generated by default as identity primary key,
  type        text not null,          -- 'event'
  item_id     bigint not null,        -- id of the event
  item_title  text,                   -- snapshot of the title
  name        text not null,
  phone       text not null,
  email       text not null,
  created_at  timestamptz default now()
);

-- Admin users (Supabase Auth emails allowed to manage the site).
-- Create the user in Authentication -> Users, then add their email here.
create table if not exists public.admin_emails (
  email       text primary key,
  created_at  timestamptz default now()
);

