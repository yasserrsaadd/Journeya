-- ============================================================
--  BOOKINGS (instant guest checkout - no accounts)
--  One row per booking; "seats" = how many spots booked.
--  "event_date" is a snapshot of the event's date AT BOOKING TIME:
--  if the admin later reschedules the event, sales made before the
--  change stay attributed to the old date in the reports.
-- ============================================================
create table if not exists public.bookings (
  id          bigint generated by default as identity primary key,
  type        text not null,          -- 'event'
  item_id     bigint not null,        -- id of the event
  item_title  text,                   -- snapshot of the title
  event_date  date,                   -- snapshot of the event date at booking time
  name        text not null,
  phone       text not null,
  email       text not null,
  tier_id     bigint,                 -- for professional events
  tier_name   text,
  tier_price  numeric,
  custom_data jsonb not null default '{}',  -- answers to custom fields (IG, job, ...)
  seats       int not null default 1,
  total       numeric,
  created_at  timestamptz default now()
);

alter table public.bookings add column if not exists tier_id     bigint;
alter table public.bookings add column if not exists tier_name   text;
alter table public.bookings add column if not exists tier_price  numeric;
alter table public.bookings add column if not exists custom_data jsonb default '{}';
alter table public.bookings add column if not exists seats       int default 1;
alter table public.bookings add column if not exists total       numeric;
alter table public.bookings add column if not exists seat_numbers int[];
alter table public.bookings add column if not exists event_date  date;

-- One-time backfill: bookings made before the snapshot existed fall back
-- to the event's current date (only fills rows that are still null).
update public.bookings b
set event_date = e.date
from public.events e
where b.type = 'event'
  and e.id = b.item_id
  and b.event_date is null;

