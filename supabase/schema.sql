-- True if the current authenticated user's email is an allowed admin.
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.admin_emails
    where lower(btrim(email)) = lower(coalesce(btrim(auth.jwt() ->> 'email'), ''))
  );
$$;

-- ============================================================
--  SHARE-LINK ACCESS (private events)
--  Private events are invisible on the public site, but a unique
--  token link can fetch them. These helpers let the public read a
--  private event ONLY when they hold the correct token.
-- ============================================================
create or replace function public.get_shared_event(p_token text)
returns table (
  id bigint, title text, event_type text, category text, summary text,
  description text, "date" date, "time" text, location text, image text, video text,
  price numeric, seats bigint, refund_policy text, guidelines text, custom_fields jsonb
)
language sql
security definer
set search_path = public
stable
as $$
  select id, title, event_type, category, summary, description, date, time, location,
         image, video, price, seats, refund_policy, guidelines, custom_fields
  from public.events
  where share_token = p_token
$$;

-- Ticket tiers for a private professional event, readable only by its token.
create or replace function public.get_shared_event_tiers(p_token text)
returns table (id bigint, name text, price numeric)
language sql
security definer
set search_path = public
stable
as $$
  select tt.id, tt.name, tt.price
  from public.ticket_tiers tt
  join public.events e on e.id = tt.event_id
  where e.share_token = p_token
$$;

-- ============================================================
--  CREATE BOOKING (guest checkout with seat-number assignment)
--  For events that have a capacity (events.seats set by the admin),
--  this assigns the next available seat numbers (1..capacity,
--  lowest free first) and refuses to overbook. It is a single
--  transaction, so two guests can never be handed the same seat.
--  Being security definer, it can read existing bookings (RLS -
--  admins only) and return the row to the guest who just booked.
-- ============================================================
create or replace function public.create_booking(
  p_item_id     bigint,
  p_name        text,
  p_phone       text,
  p_email       text,
  p_type        text   default 'event',
  p_item_title  text   default null,
  p_tier_id     bigint  default null,
  p_tier_name   text    default null,
  p_tier_price  numeric default null,
  p_custom_data jsonb   default '{}',
  p_seats       int     default 1,
  p_total       numeric default null
)
returns public.bookings
language plpgsql
security definer
set search_path = public
as $$
declare
  v_capacity     bigint;
  v_event_date   date;
  v_used         int[] := '{}';
  v_free         int[] := '{}';
  v_seat_numbers int[];
  v_booking      public.bookings;
begin
  -- Lock the event row so concurrent bookings for the same event
  -- are serialized and cannot compute the same seat numbers.
  -- The event's date is snapshotted here too, so this booking keeps
  -- reporting against the date the guest actually booked it for.
  select e.seats, e.date into v_capacity, v_event_date
  from public.events e
  where e.id = p_item_id
  for update;

  if v_capacity is not null then
    -- Every already-assigned number for this event.
    select coalesce(array_agg(s), '{}') into v_used
    from (
      select unnest(b.seat_numbers) as s
      from public.bookings b
      where b.type = 'event'
        and b.item_id = p_item_id
        and b.seat_numbers is not null
    ) u;

    -- Free numbers = 1..capacity minus whatever is taken.
    select array_agg(n::int order by n) into v_free
    from generate_series(1, v_capacity) n
    where not (n = any(v_used));

    if coalesce(cardinality(v_free), 0) < p_seats then
      raise exception 'Not enough seats available for this event (only % of % left).',
        coalesce(cardinality(v_free), 0), v_capacity;
    end if;

    -- Hand out the lowest available numbers first.
    v_seat_numbers := v_free[1:p_seats];
  end if;

  insert into public.bookings (
    type, item_id, item_title, event_date, name, phone, email,
    tier_id, tier_name, tier_price, custom_data, seats, total, seat_numbers
  ) values (
    p_type, p_item_id, p_item_title, v_event_date, p_name, p_phone, p_email,
    p_tier_id, p_tier_name, p_tier_price,
    coalesce(p_custom_data, '{}'), p_seats, p_total, v_seat_numbers
  )
  returning * into v_booking;

  return v_booking;
end;
$$;

-- ============================================================
--  ROW LEVEL SECURITY
--  Public can READ non-private events and create bookings via
--  the create_booking RPC (guest checkout - no login required).
--  Only authenticated admins can create/update/delete events,
--  manage tiers, or read the guest lists.
-- ============================================================
alter table public.events        enable row level security;
alter table public.ticket_tiers  enable row level security;
alter table public.bookings      enable row level security;
alter table public.admin_emails  enable row level security;

--  Older versions of this file created a fully permissive policy
--  ("public read events" ... using (true)). RLS policies are OR-ed,
--  so if that leftover is still on the project, private events stay
--  readable by everyone. Drop EVERY existing read policy on events
--  first, then recreate the correct ones below. (Safe to re-run.)
do $$
declare pol record;
begin
  for pol in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename  = 'events'
      and cmd in ('SELECT', '*')
  loop
    execute format('drop policy if exists %I on public.events', pol.policyname);
  end loop;
end $$;

-- A NULL is_private never matches "is_private = false", so old rows
-- would silently disappear from the public site. Normalize them.
update public.events set is_private = false where is_private is null;

-- --- events ---
-- Guests (and signed-in non-admins) see public events ONLY.
create policy "public read public events" on public.events
  for select using (is_private = false);

-- Admins see everything, private events included.
create policy "admin read all events" on public.events
  for select to authenticated using (public.is_admin());

drop policy if exists "admin insert events" on public.events;
create policy "admin insert events" on public.events for insert with check (public.is_admin());
drop policy if exists "admin update events" on public.events;
create policy "admin update events" on public.events for update using (public.is_admin());
drop policy if exists "admin delete events" on public.events;
create policy "admin delete events" on public.events for delete using (public.is_admin());

-- --- ticket tiers (visible only for public events, or to admins) ---
do $$
declare pol record;
begin
  for pol in
    select policyname
    from pg_policies
    where schemaname = 'public'
      and tablename  = 'ticket_tiers'
      and cmd in ('SELECT', '*')
  loop
    execute format('drop policy if exists %I on public.ticket_tiers', pol.policyname);
  end loop;
end $$;

create policy "public read tiers" on public.ticket_tiers for select
  using (
    exists (
      select 1 from public.events e
      where e.id = ticket_tiers.event_id and e.is_private = false
    )
  );

create policy "admin read tiers" on public.ticket_tiers
  for select to authenticated using (public.is_admin());

drop policy if exists "admin insert tiers" on public.ticket_tiers;
create policy "admin insert tiers" on public.ticket_tiers for insert with check (public.is_admin());
drop policy if exists "admin update tiers" on public.ticket_tiers;
create policy "admin update tiers" on public.ticket_tiers for update using (public.is_admin());
drop policy if exists "admin delete tiers" on public.ticket_tiers;
create policy "admin delete tiers" on public.ticket_tiers for delete using (public.is_admin());

