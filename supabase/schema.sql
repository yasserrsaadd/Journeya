-- ============================================================
--  EVENTS (game nights / social gatherings)
--  Both "Regular" (uniform price) and "Professional" (multi-tier
--  tickets + custom fields) events live here.
-- ============================================================
create table if not exists public.events (
  id          bigint generated by default as identity primary key,
  title       text not null,
  event_type  text not null default 'regular',   -- 'regular' | 'professional'
  category    text,
  summary     text,
  description text,
  date        date,
  time        text,
  location    text,
  image       text,
  video       text,
  price       numeric,
  seats       bigint,                            -- optional total seats (seat-number assignment)
  refund_policy text,
  guidelines  text,
  is_private  boolean not null default false,
  share_token text,
  custom_fields jsonb not null default '[]',     -- [{label, required}] for professional events
  created_at  timestamptz default now()
);

