alter table public.events add column if not exists is_private    boolean default false;
alter table public.events add column if not exists share_token   text;
alter table public.events add column if not exists custom_fields jsonb default '[]';

-- Unique share tokens (runs AFTER the migration above, so the column
-- exists whether the table is brand-new or pre-existing)
create unique index if not exists events_share_token_key
  on public.events (share_token) where share_token is not null;

-- ============================================================
--  TICKET TIERS (multi-tier pricing for professional events)
-- ============================================================
create table if not exists public.ticket_tiers (
  id         bigint generated by default as identity primary key,
  event_id   bigint not null references public.events(id) on delete cascade,
  name       text not null,
  price      numeric not null,
  created_at timestamptz default now()
);

-- ============================================================
--  BOOKINGS (instant guest checkout - no accounts)
--  One row per booking; "seats" = how many spots booked.
-- ============================================================
create table if not exists public.bookings (
  id          bigint generated by default as identity primary key,
  type        text not null,          -- 'event'
  item_id     bigint not null,        -- id of the event
  item_title  text,                   -- snapshot of the title
  name        text not null,
  phone       text not null,
  email       text not null,
  tier_id     bigint,                 -- for professional events
  tier_name   text,
  tier_price  numeric,
  custom_data jsonb not null default '{}',  -- answers to custom fields (IG, job, ...)
  seats       int not null default 1,
  total       numeric,
  created_at  timestamptz default now()
);

alter table public.bookings add column if not exists tier_id     bigint;
